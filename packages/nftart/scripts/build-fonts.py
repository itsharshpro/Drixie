#!/usr/bin/env python3
"""Subset Geist + Geist Mono (SIL OFL 1.1) for embedding in NFT SVGs.

Keeps printable ASCII plus a few typographic marks, limits the weight axis to 400-700 and writes
  fonts/geist-subset.woff2, fonts/geist-mono-subset.woff2   (inspectable copies)
  src/fonts.generated.ts                                   (base64, imported by the renderers)
Source fonts: the Geist latin woff2 files that ship with Next.js (apps/web/node_modules/next/...).
Run: pnpm --filter @listed/nftart fonts
"""
import base64
import io
import os
import sys

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
ROOT = os.path.dirname(os.path.dirname(PKG))
SRC = os.path.join(ROOT, "apps/web/node_modules/next/dist/next-devtools/server/font")
TEXT = "".join(chr(c) for c in range(0x20, 0x7F)) + "·—–−’‘“”…×•→№"


def build(src_name: str, out_name: str) -> bytes:
    font = TTFont(os.path.join(SRC, src_name))
    font = instancer.instantiateVariableFont(font, {"wght": (400, 700)})
    # Round-trip so the subsetter sees fully loaded tables after instancing.
    tmp = io.BytesIO()
    font.flavor = None
    font.save(tmp)
    tmp.seek(0)
    font = TTFont(tmp)
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["kern", "tnum", "liga", "calt"]
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    sub = subset.Subsetter(opts)
    sub.populate(text=TEXT)
    sub.subset(font)
    buf = io.BytesIO()
    font.flavor = "woff2"
    font.save(buf)
    data = buf.getvalue()
    with open(os.path.join(PKG, "fonts", out_name), "wb") as f:
        f.write(data)
    return data


def main() -> int:
    sans = build("geist-latin.woff2", "geist-subset.woff2")
    mono = build("geist-mono-latin.woff2", "geist-mono-subset.woff2")
    ts = (
        "// Generated by scripts/build-fonts.py — do not edit. Geist and Geist Mono (SIL Open Font License 1.1),\n"
        "// subset to printable ASCII + a few marks, weight axis 400-700, woff2, base64.\n"
        f'export const GEIST_WOFF2 = "{base64.b64encode(sans).decode()}";\n'
        f'export const GEIST_MONO_WOFF2 = "{base64.b64encode(mono).decode()}";\n'
    )
    with open(os.path.join(PKG, "src", "fonts.generated.ts"), "w") as f:
        f.write(ts)
    print(f"geist {len(sans)} B, geist mono {len(mono)} B")
    return 0


if __name__ == "__main__":
    sys.exit(main())
